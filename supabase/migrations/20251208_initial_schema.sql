create policy "company members can read companies" on public.companies
  for select using (public.is_company_member(id));

create policy "company members manage members" on public.company_members
  for all using (public.is_company_member(company_id));

create policy "company members manage vehicles" on public.vehicles
  for all using (public.is_company_member(company_id));

create policy "company members read routes" on public.routes
  for select using (public.is_company_member(company_id));

create policy "company members manage routes" on public.routes
  for all using (
    public.is_company_member(company_id)
    and exists (
      select 1 from public.company_members cm
      where cm.company_id = routes.company_id
        and (
          cm.id = routes.driver_id
          or (cm.user_id = auth.uid() and cm.role in ('dispatcher', 'admin'))
        )
    )
  );

create policy "company members read tasks" on public.tasks
  for select using (public.is_company_member(company_id));

create policy "dispatchers update tasks" on public.tasks
  for all using (
    public.is_company_member(company_id)
    and exists (
      select 1 from public.company_members cm
      where cm.user_id = auth.uid()
        and cm.company_id = tasks.company_id
        and cm.role in ('dispatcher', 'admin')
    )
  );

create policy "drivers update own tasks" on public.tasks
  for update using (
    public.is_company_member(company_id)
    and driver_id in (
      select id from public.company_members
      where company_id = tasks.company_id
        and user_id = auth.uid()
    )
  );

create policy "company members read route tasks" on public.route_tasks
  for select using (public.is_company_member(company_id));

create policy "company members read telemetry" on public.telemetry_events
  for select using (public.is_company_member(company_id));

create policy "drivers insert telemetry" on public.telemetry_events
  for insert with check (
    public.is_company_member(company_id)
    and driver_id in (
      select id from public.company_members
      where company_id = public.telemetry_events.company_id
        and user_id = auth.uid()
    )
  );

create policy "company members manage sync queue" on public.sync_queue_items
  for all using (public.is_company_member(company_id));

create policy "company members manage media" on public.media_artifacts
  for all using (public.is_company_member(company_id));

create policy "company members read notifications" on public.notifications
  for select using (public.is_company_member(company_id));

