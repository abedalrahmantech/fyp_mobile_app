-- Helper functions ------------------------------------------------------------
create or replace function public.is_company_member(target_company_id uuid)
returns boolean
language sql
stable
as $$
  select exists (
    select 1
    from public.company_members cm
    where cm.company_id = target_company_id
      and cm.user_id = auth.uid()
  );
$$;

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Core tables -----------------------------------------------------------------
create table if not exists public.companies (
  id uuid primary key default uuid_generate_v4(),
  name text not null,
  timezone text not null default 'Asia/Hong_Kong',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.company_members (
  id uuid primary key default uuid_generate_v4(),
  user_id uuid not null references auth.users(id) on delete cascade,
  company_id uuid not null references public.companies(id) on delete cascade,
  role text not null check (role in ('driver', 'dispatcher', 'admin')),
  invited_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, company_id)
);

create table if not exists public.vehicles (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  driver_id uuid references public.company_members(id) on delete set null,
  label text not null,
  plate text,
  capacity_kg numeric,
  active_route_id uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.routes (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  vehicle_id uuid references public.vehicles(id) on delete set null,
  driver_id uuid references public.company_members(id) on delete set null,
  status text not null default 'draft',
  optimizer text not null default 'manual',
  started_at timestamptz,
  completed_at timestamptz,
  eta_summary jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.tasks (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  external_ref text,
  vehicle_id uuid references public.vehicles(id) on delete set null,
  driver_id uuid references public.company_members(id) on delete set null,
  address text not null,
  notes text,
  location geography(point, 4326),
  status text not null default 'pending',
  priority integer default 0,
  scheduled_start timestamptz,
  scheduled_end timestamptz,
  proof_code text,
  proof_photo_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.route_tasks (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  route_id uuid not null references public.routes(id) on delete cascade,
  task_id uuid not null references public.tasks(id) on delete cascade,
  sequence integer not null,
  planned_arrival timestamptz,
  planned_departure timestamptz,
  travel_distance_m integer,
  travel_duration_s integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (route_id, task_id),
  unique (route_id, sequence)
);

create table if not exists public.telemetry_events (
  id bigint generated by default as identity primary key,
  company_id uuid not null references public.companies(id) on delete cascade,
  driver_id uuid not null references public.company_members(id) on delete cascade,
  vehicle_id uuid references public.vehicles(id) on delete set null,
  task_id uuid references public.tasks(id) on delete set null,
  recorded_at timestamptz not null default now(),
  location geography(point, 4326) not null,
  speed_kph numeric,
  heading numeric,
  battery numeric,
  source text not null default 'device',
  payload jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.sync_queue_items (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  driver_id uuid not null references public.company_members(id) on delete cascade,
  action_type text not null,
  payload jsonb not null,
  status text not null default 'pending',
  attempts integer not null default 0,
  last_attempt_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.media_artifacts (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  task_id uuid references public.tasks(id) on delete cascade,
  driver_id uuid references public.company_members(id) on delete set null,
  type text not null,
  storage_path text not null,
  checksum text,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.geofence_rules (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  name text not null,
  geometry geography,
  radius_m integer,
  center geography(point, 4326),
  trigger text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id uuid primary key default uuid_generate_v4(),
  company_id uuid not null references public.companies(id) on delete cascade,
  sender_id uuid references public.company_members(id) on delete set null,
  recipient_id uuid references public.company_members(id) on delete set null,
  message text not null,
  metadata jsonb,
  delivered_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  company_id uuid references public.companies(id) on delete cascade,
  actor_id uuid,
  action text not null,
  description text,
  metadata jsonb,
  created_at timestamptz not null default now()
);

-- Views -----------------------------------------------------------------------
create or replace view public.route_assignments as
select
  r.id as route_id,
  r.company_id,
  r.driver_id,
  array_agg(rt.task_id order by rt.sequence) as task_ids
from public.routes r
join public.route_tasks rt on rt.route_id = r.id
group by r.id;

-- Triggers --------------------------------------------------------------------
create or replace function public.install_touch_triggers(target_table regclass) returns void
language plpgsql as $$
begin
  execute format('create trigger %s_touch before update on %s
    for each row execute procedure public.touch_updated_at()',
    target_table::text, target_table::text);
exception when duplicate_object then
  null;
end;
$$;

